export const messages: Record<Lang, Record<string, string>> = { ru, ua, en };

export function isLang(value: string | undefined): value is Lang {
  return value === "ru" || value === "ua" || value === "en";
}

export function localeForLang(lang: Lang): string {
  return lang === "ua" ? "uk-UA" : lang === "en" ? "en-US" : "ru-RU";
}

export function translate(lang: Lang, key: string, vars: TranslateVars = {}): string {
  const template = messages[lang][key] ?? messages.ru[key] ?? key;
  return Object.entries(vars).reduce(
    (value, [name, replacement]) => value.split(`{${name}}`).join(String(replacement)),
    template,
  );
}
